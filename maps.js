const stairs = (ax, c, edge, dir, n, w, mat, y0 = 0) => {
  const o = [];
  for (let i = 0; i < n; i++) { const p = edge - dir * ((n - 1 - i) * 0.9 + 0.45); o.push(ax === 'z' ? B(c, p, w, 0.9, (i + 1) * 0.4, mat, y0) : B(p, c, 0.9, w, (i + 1) * 0.4, mat, y0)); }
  return o;
};
